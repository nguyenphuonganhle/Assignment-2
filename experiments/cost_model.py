import argparse, csv, os, statistics as st
from collections import defaultdict
FF, EK= "Ford-Fulkerson", "Edmonds-Karp"
def load(d):
    inst= {int(r["instance"]): r for r in csv.DictReader(open(os.path.join(d, "instances.csv")))}
    times= defaultdict(list)
    for r in csv.DictReader(open(os.path.join(d, "raw_trials.csv"))):
        times[int(r["instance"]), r["algo"]].append(float(r["time_s"]))
    rows= []                                      
    for i, r in inst.items():
        for algo in (FF, EK):
            rows.append((int(r["seed"]), i, r["family"], float(r["x"]), algo, st.median(times[i, algo]),
                         float(r[f"{algo}:edge_scans"]), float(r[f"{algo}:path_len_total"])))
    return rows
def fit(train, columns):
    rows= [[c / x[5] for c in columns(x)] for x in train]
    k= len(rows[0])
    A= [[sum(r[i] * r[j] for r in rows) for j in range(k)] for i in range(k)]
    b= [sum(r[i] for r in rows) for i in range(k)]
    if k==1:
        return [b[0] / A[0][0]]
    det= A[0][0] * A[1][1] - A[0][1] * A[1][0]
    return [(b[0] * A[1][1] - b[1] * A[0][1]) / det, (A[0][0] * b[1] - A[1][0] * b[0]) / det]
def main():
    ap= argparse.ArgumentParser(); ap.add_argument("--dir", default="results"); d = ap.parse_args().dir
    rows= load(d)
    train= [x for x in rows if x[0] <= 1]
    test= [x for x in rows if x[0] >= 2]
    if not test:
        print("cost_model: needs seeds >= 2 (use the full run, not --quick); skipped.")
        return
    cols_a= lambda x: [x[6]]
    cols_b= lambda x: [x[6], x[7]]
    wa, wb= fit(train, cols_a), fit(train, cols_b)
    predict= lambda w, cols, x: sum(a * c for a, c in zip(w, cols(x)))
    err= lambda w, cols: st.median([abs(predict(w, cols, x) - x[5]) / x[5] for x in test])
    L= ["# Cost model check (generated by experiments/cost_model.py)", "",
         f"Fitted on {len(train)} runs (seeds 0-1), tested on {len(test)} runs (seeds 2-4) that were never used for fitting.", "",
         "| Model | Fitted numbers | Median error on test runs |", "|---|---|---|",
         f"| A: time = a x scans | a = {wa[0]:.2e} s per scan | {err(wa, cols_a) * 100:.0f}% |",
         f"| B: time = a x scans + b x path edges | a = {wb[0]:.2e} s per scan, b = {wb[1]:.2e} s per path edge | {err(wb, cols_b) * 100:.0f}% |", ""]
    L+= ["## Crossover on the matching network (seeds 2-4 only)", "",
          "| C | measured FF/EK | model A FF/EK | model B FF/EK |", "|---|---|---|---|"]
    by= defaultdict(lambda: defaultdict(dict))
    for x in test:
        if x[2]=="matching_crossover":
            by[x[3]][x[1]][x[4]] = x
    cross= {"measured": None, "A": None, "B": None}
    for c in sorted(by):
        m, pa, pb= [], [], []
        for i, pair in by[c].items():
            m.append(pair[FF][5] / pair[EK][5])
            pa.append(predict(wa, cols_a, pair[FF]) / predict(wa, cols_a, pair[EK]))
            pb.append(predict(wb, cols_b, pair[FF]) / predict(wb, cols_b, pair[EK]))
        vals= {"measured": st.median(m), "A": st.median(pa), "B": st.median(pb)}
        for k, v in vals.items():
            if cross[k] is None and v > 1:
                cross[k]= c
        L.append(f"| {c:g} | {vals['measured']:.2f} | {vals['A']:.2f} | {vals['B']:.2f} |")
    L+= ["", "First C where EK is faster (ratio above 1): " + ", ".join(
        f"{k} = {'none' if v is None else format(v, 'g')}" for k, v in cross.items()), ""]
    open(os.path.join(d, "cost_model.md"), "w").write("\n".join(L))
    print("\n".join(L))
    
if __name__ == "__main__":
    main()

import argparse, csv, os, statistics as st
from collections import defaultdict
def main():
    ap= argparse.ArgumentParser(); ap.add_argument("--dir", default="results"); d = ap.parse_args().dir
    inst= {r["instance"]: r for r in csv.DictReader(open(os.path.join(d, "instances.csv")))}
    times= defaultdict(list)
    for r in csv.DictReader(open(os.path.join(d, "raw_trials.csv"))):
        times[r["instance"], r["algo"]].append(float(r["time_s"]))
    fam= defaultdict(lambda: dict(n=0, over15=0, over2=0, worst=(0, ""), mean_over_median=[]))
    for (i, algo), ts in times.items():
        m= st.median(ts)
        f= fam[inst[i]["family"]]
        f["mean_over_median"].append(st.mean(ts) / m)
        for t in ts:
            f["n"] += 1; f["over15"] += t > 1.5 * m; f["over2"] += t > 2 * m
            if t / m > f["worst"][0]:
                f["worst"] = (t / m, f"{algo}, x = {inst[i]['x']}, seed {inst[i]['seed']}")
    total= sum(f["n"] for f in fam.values()); o15 = sum(f["over15"] for f in fam.values()); o2 = sum(f["over2"] for f in fam.values())
    L= ["# Timing outliers (generated by experiments/outliers.py)", "",
         f"{total} timed runs. A run is compared with the median of the repetitions of the same instance and algorithm. "
         f"Overall {100 * o15 / total:.1f}% of runs are more than 1.5 times their median and {100 * o2 / total:.1f}% more than 2 times.", "",
         "| family | runs | above 1.5x median | above 2x median | worst run / median | mean / median (typical instance) |", "|---|---|---|---|---|---|"]
    for name, f in fam.items():
        L.append(f"| {name} | {f['n']} | {100 * f['over15'] / f['n']:.1f}% | {100 * f['over2'] / f['n']:.1f}% | "
                 f"{f['worst'][0]:.1f} ({f['worst'][1]}) | {st.median(f['mean_over_median']):.2f} |")
    open(os.path.join(d, "outliers.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))

if __name__ == "__main__":
    main()

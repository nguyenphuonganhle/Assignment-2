import argparse, csv, os, statistics as st
from collections import defaultdict
FF, EK= "Ford-Fulkerson", "Edmonds-Karp"
def main():
    ap= argparse.ArgumentParser(); ap.add_argument("--dir", default="results"); d= ap.parse_args().dir
    rows= list(csv.DictReader(open(os.path.join(d, "instances.csv"))))
    groups, broken= defaultdict(list), 0
    for r in rows:
        v, e, f= float(r["nodes"]), float(r["edges"]), float(r["flow_value"])
        ff, ek= float(r[f"{FF}:augmentations"]), float(r[f"{EK}:augmentations"])
        if ff>f or ek>v * e / 2:
            broken+=1
        groups[r["family"], float(r["x"])].append((v, e, f, ff, ek))
    L= ["# How tight are the bounds? (generated by experiments/bounds.py)", "",
         f"Hard check on all {len(rows)} instances: FF augmentations <= F and EK augmentations <= V*E/2. Violations found: {broken}.", "",
         "Medians over seeds. `FF / F` and `EK / (VE/2)` show how much of each bound the algorithm actually uses (1.0 = bound reached).", "",
         "| family | x | V | E | F | FF paths | FF / F | EK paths | EK / (VE/2) |", "|---|---|---|---|---|---|---|---|---|"]
    for (fam, x) in sorted(groups, key=lambda k: (list(dict.fromkeys(r['family'] for r in rows)).index(k[0]), k[1])):
        g= [t for t in groups[fam, x] if t[2] > 0]
        if not g:
            continue
        med= lambda i: st.median([t[i] for t in g])
        ffr= st.median([t[3] / t[2] for t in g]); ekr= st.median([t[4] / (t[0] * t[1] / 2) for t in g])
        L.append(f"| {fam} | {x:g} | {med(0):.0f} | {med(1):.0f} | {med(2):.0f} | {med(3):.0f} | {ffr:.3g} | {med(4):.0f} | {ekr:.2g} |")
    open(os.path.join(d, "bounds.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))

if __name__ == "__main__":
    main()
